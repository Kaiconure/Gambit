local loader = dofile('lib/variable-loader.lua')
local warnings = {}
local state = loader.new(function(s) warnings[#warnings+1] = s end)
local vars = {}
state.merge(vars, {enabled=false, keep={spells={'Silence'},targets={'Old'}}, ordinary=1}, 'base')
state.merge(vars, {['!enabled']=true, ['!keep']={targets={'New'}}}, 'namespace')
state.merge(vars, {enabled=false, keep={spells={'Other'},targets={'Later'},extra=3}, ordinary=2}, 'library')
assert(vars.enabled and vars.ordinary==1)
assert(vars.keep.spells[1]=='Silence' and vars.keep.targets[1]=='New' and vars.keep.extra==3)
state.merge(vars, {['!enabled']=false}, 'conflict')
assert(vars.enabled and #warnings==1 and warnings[1]:find('namespace',1,true))
state.merge(vars, {keep='$object.empty',enabled='$object.null'}, 'clear')
assert(vars.enabled and vars.keep.targets[1]=='New')
state.merge(vars, {['!deleted']='$object.null',['!empty']='$array.empty'}, 'clear')
state.merge(vars, {deleted={x=1},empty={1,2}}, 'defaults')
assert(vars.deleted==nil and next(vars.empty)==nil)
state.merge(vars, {['!nested']={['!x']=false},nested={x=true,y=2}}, 'same-file')
assert(vars.nested.x==false and vars.nested.y==2 and vars['!nested']==nil)
state.merge(vars, {nested={z=4}}, 'later')
assert(vars.nested.z==4)
vars.enabled=false -- Runtime assignments remain ordinary writes.
assert(vars.enabled==false)
local reverse = {}; local other=loader.new()
other.merge(reverse,{['!keep']={targets={'New'}}},'namespace')
other.merge(reverse,{keep={targets={'Old'},spells={'Silence'}}},'library')
assert(reverse.keep.targets[1]=='New' and reverse.keep.spells[1]=='Silence')
local legacy={}; local normal=loader.new()
normal.merge(legacy,{a={},b=false,c={1,2},object={x=1}},'base')
normal.merge(legacy,{a={3},b=true,c={4},object={y=2}},'import')
assert(legacy.a[1]==3 and legacy.b==false and legacy.c[2]==2 and legacy.object.y==2)
normal.merge(legacy,{c='$array.empty',b='$object.null'},'clear')
assert(next(legacy.c)==nil and legacy.b==nil)
print('PASS: variable priority, nested defaults, arrays, clearing, conflicts, same-file order and runtime writes')

local Loader=require('./lib/variable-loader')
local function state()
 local vars,warnings={},{}
 local loader=Loader.new(function(s)warnings[#warnings+1]=s end)
 return vars,function(value)loader.merge(vars,value,'layer')end,warnings
end
local vars,merge,warnings=state()
merge({use_dispel={['array.append(buffs)']={'Blaze Spikes','Howl','Howl'}}})
assert(table.concat(vars.use_dispel.buffs,',')=='Blaze Spikes,Howl')
merge({use_dispel={buffs={'Protect','Howl','Protect'}}})
assert(table.concat(vars.use_dispel.buffs,',')=='Protect,Howl,Blaze Spikes')
merge({unrelated=true})
assert(table.concat(vars.use_dispel.buffs,',')=='Protect,Howl,Blaze Spikes')
assert(#warnings==0 and vars.use_dispel['array.append(buffs)']==nil)
vars,merge,warnings=state()
merge({buffs={'Protect'},['array.append(buffs)']={'Howl','Protect'}})
assert(table.concat(vars.buffs,',')=='Protect,Howl')
merge({['array.append(buffs)']={'Blaze Spikes','Howl'}})
assert(table.concat(vars.buffs,',')=='Protect,Blaze Spikes,Howl') -- Parent additions precede child additions.
for _,base in ipairs({false,42,'text',{named=true}})do
 vars,merge,warnings=state()
 merge({buffs=base})
 merge({['array.append(buffs)']={'Howl'}})
 assert(type(vars.buffs)==type(base) and #warnings==1)
 merge({unrelated=1});assert(#warnings==1)
end
vars,merge,warnings=state()
merge({['array.append(buffs)']={'Howl'}})
merge({buffs=false});assert(vars.buffs==false and #warnings==1)
vars,merge,warnings=state()
merge({['array.append(buffs)']={named=true}})
assert(vars.buffs==nil and #warnings==1)
vars,merge,warnings=state()
merge({['array.append(buffs)']={}});assert(type(vars.buffs)=='table' and next(vars.buffs)==nil)
merge({buffs={'Protect'}});assert(vars.buffs[1]=='Protect')
vars,merge,warnings=state()
merge({['csv(a, b)']={['array.append(buffs)']={{id=1},{id=1},'Howl'}}})
merge({a={buffs={{id=1},{id=2}}}})
assert(#vars.a.buffs==3 and #vars.b.buffs==2)
vars.a.buffs[1].id=99;assert(vars.b.buffs[1].id==1)
-- Clears retain their priority, including when the replacement is nil/empty.
for _,marker in ipairs({'$object.null','$table.null','$array.empty','$object.empty','$table.empty'})do
 vars,merge,warnings=state()
 merge({buffs=marker})
 merge({buffs={'Protect'},['array.append(buffs)']={'Howl'}})
 assert(vars.buffs==nil or next(vars.buffs)==nil)
 merge({['!array.append(buffs)']={'Howl'}})
 assert(vars.buffs[1]=='Howl')
end
vars,merge,warnings=state()
merge({['!buffs']={'Protect'}})
merge({['array.append(buffs)']={'Howl'}})
assert(#vars.buffs==1)
vars,merge,warnings=state()
merge({['^buffs']='$object.null'})
merge({buffs={'Protect'}});assert(vars.buffs[1]=='Protect')
merge({['!buffs']='$object.null'});assert(vars.buffs==nil)
merge({buffs={'Howl'}});assert(vars.buffs==nil)
print('PASS: distinct array appends, inherited bases, repeated layers, CSV composition, copy isolation, invalid types/warnings, clear and priority semantics')

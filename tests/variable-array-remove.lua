local Loader=require('./lib/variable-loader')
local function state()
 local vars,warnings={},{}
 local loader=Loader.new(function(s)warnings[#warnings+1]=s end)
 return vars,function(value)loader.merge(vars,value,'test')end,warnings
end
local vars,merge,warnings=state()
merge({['array.remove(buffs)']={'Howl','Howl'}})
assert(vars.buffs==nil)
merge({buffs={'Protect','Howl','Shell','Howl'}})
assert(table.concat(vars.buffs,',')=='Protect,Shell')
merge({unrelated=true});assert(table.concat(vars.buffs,',')=='Protect,Shell' and #warnings==0)
for _,base in ipairs({false,42,'text',{named=true}})do
 vars,merge,warnings=state()
 merge({buffs=base});merge({['array.remove(buffs)']={'Howl'}})
 assert(type(vars.buffs)==type(base) and #warnings==1)
 merge({unrelated=true});assert(#warnings==1)
end
vars,merge,warnings=state()
merge({['array.remove(buffs)']={invalid=true}})
assert(vars.buffs==nil and #warnings==1)
vars,merge,warnings=state()
merge({['array.append(buffs)']={'Howl','Protect'},['array.remove(buffs)']={'Howl'}})
assert(table.concat(vars.buffs,',')=='Protect')
merge({['array.append(buffs)']={'Howl','Shell'}}) -- Lower-precedence additions still get filtered.
assert(table.concat(vars.buffs,',')=='Shell,Protect')
vars,merge,warnings=state()
merge({['array.append(buffs)']={'Howl'}})
merge({['array.remove(buffs)']={'Howl'},buffs={'Howl','Protect'}})
assert(table.concat(vars.buffs,',')=='Protect,Howl') -- Child can re-add a parent's removal.
vars,merge,warnings=state()
merge({['csv(a, b)']={['array.remove(buffs)']={{id=1}}}})
merge({a={buffs={{id=1},{id=2},{id=1}}},b={buffs={{id=1},{id=3}}}})
assert(#vars.a.buffs==1 and vars.a.buffs[1].id==2)
assert(#vars.b.buffs==1 and vars.b.buffs[1].id==3)
vars,merge,warnings=state()
merge({['!buffs']={'Howl','Protect'}})
merge({['array.remove(buffs)']={'Howl'}});assert(#vars.buffs==2)
merge({['!array.remove(buffs)']={'Howl'}});assert(#vars.buffs==1 and vars.buffs[1]=='Protect')
vars,merge,warnings=state()
merge({buffs='$object.null'});merge({['array.remove(buffs)']={'Howl'}});assert(vars.buffs==nil)
assert(not pcall(merge,{['array.remove()']={}}))
assert(not pcall(merge,{['array.remove(buffs']={}}))
print('PASS: array removal of all matches, nil/non-array handling, structural equality, CSV, inheritance, same-layer remove wins and priorities')

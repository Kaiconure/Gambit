local file = assert(io.open('lib/action-context.lua'))
local source = file:read('*a')
file:close()
local body = assert(source:match('(context.execute = function%(code, %.%.%.%).-)    %-%- "Static" context properties'))
local context = {calls = 0}
context.touch = function() context.calls = context.calls + 1; return true end
context.fail = function() error('expected condition failure') end
local chunk = assert(loadstring(body))
setfenv(chunk, setmetatable({context=context, executionFactory=dofile('lib/execution-factory.lua')}, {__index=_G}))
chunk()
assert(context.evaluateAll(true) == true)
assert(context.evaluateAll(false) == false)
assert(context.evaluateAll(nil) == false)
assert(context.evaluateAll(0) == true)
assert(context.evaluateAll({}) == false)
assert(context.evaluateAll('true') == true)
assert(context.evaluateAll('nil') == false)
assert(context.evaluateAll({'false', 'touch()'}) == false and context.calls == 0)
assert(context.evaluateAll({'touch()', 'true'}) == true and context.calls == 1)
assert(context.evaluateAll({true, false, 'touch()'}) == false and context.calls == 1)
assert(context.evaluateAll('... == 7', 7) == true)
assert(not pcall(context.evaluateAll, 'fail()'))
assert(not pcall(context.evaluateAll, {name='true'}))
assert(not pcall(context.evaluateAll, {[1]='true',[3]='true'}))
assert(context.execute({'false', 'true'}) == true)
assert(context.execute(false) == false)
assert(context.evaluateAllConditions(nil) == true)
assert(context.evaluateAllConditions({}) == true)
assert(context.evaluateAllConditions(false) == false)
assert(context.evaluateAllConditions(0) == true)
assert(context.evaluateAllConditions('nil') == false)
assert(context.evaluateAllConditions('... == 7', 7) == true)
assert(context.evaluateAllConditions({'false', 'touch()'}) == false and context.calls == 1)
assert(context.evaluateAllConditions({true, 'true'}) == true)
assert(not pcall(context.evaluateAllConditions, 'fail()'))
assert(not pcall(context.evaluateAllConditions, {name='true'}))
assert(not pcall(context.evaluateAllConditions, {[1]='true',[3]='true'}))
print('PASS: evaluateAll scalar/array semantics, short-circuiting, arguments, errors and unchanged execute')
print('PASS: evaluateAllConditions optional inputs, explicit false, forwarding, short-circuiting and errors')
